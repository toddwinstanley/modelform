#!/usr/bin/env node
// Generates <app>/dashboards/index.ts from the *.json files beside it.
// Plain CommonJS so metro.config.js and the `dashkit` bin can load it without a build step.
const fs = require('node:fs');
const path = require('node:path');

const INDEX = 'index.ts';

const HEADER = `// Generated by @spaghetti/dashkit from the *.json files in this folder. Do not edit:
// add, rename or delete a .json file instead. \`expo start\` regenerates this file
// (see metro.config.js); run \`pnpm dashboards\` to regenerate it by hand.
//
// Export a dashboard from Grafana (Share → Export → JSON) and drop the file here.
// Exports made with "Export for sharing externally" reference datasources as \${DS_NAME};
// those resolve to the first datasource of the matching type in your Grafana.
`;

/** Dashboard ids are file names without `.json`, sorted so output is stable. */
function listDashboards(dir) {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((file) => ({ id: file.slice(0, -'.json'.length), file }));
}

function renderIndex(entries) {
  const key = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id.replace(/'/g, "\\'")}'`);
  const ids = entries.length ? entries.map((e) => `'${e.id}'`).join(' | ') : 'never';
  const rows = entries.map((e) => `  ${key(e.id)}: require('./${e.file}'),\n`).join('');
  return `${HEADER}
import type { Dashboard } from '@spaghetti/dashkit';

export type BundledId = ${ids};

// require() rather than import so JSON edits hot-reload while \`expo start\` runs.
export const bundled: Record<string, Dashboard> = {
${rows}};
`;
}

/** Writes dir/index.ts if its contents would change. Returns true when it wrote. */
function writeIndex(dir) {
  const out = path.join(dir, INDEX);
  const next = renderIndex(listDashboards(dir));
  const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
  if (prev === next) return false;
  fs.writeFileSync(out, next);
  return true;
}

/**
 * Generates the index now, then again whenever a .json file is added, removed or renamed.
 * The watcher is unref'd so one-shot commands like `expo export` still exit.
 */
function watchDashboards(dir, log = console.log) {
  const run = () => {
    try {
      if (writeIndex(dir)) log(`dashkit: regenerated ${path.relative(process.cwd(), path.join(dir, INDEX))}`);
    } catch (e) {
      log(`dashkit: could not generate ${INDEX} in ${dir}: ${e.message}`);
    }
  };
  run();
  let timer;
  const watcher = fs.watch(dir, (_event, name) => {
    if (name && !String(name).endsWith('.json')) return;
    clearTimeout(timer);
    timer = setTimeout(run, 50);
  });
  watcher.unref();
  return watcher;
}

module.exports = { listDashboards, renderIndex, writeIndex, watchDashboards };

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args[0] !== 'dashboards') {
    console.error('usage: dashkit dashboards [dir] [--watch]');
    process.exit(1);
  }
  const watch = args.includes('--watch');
  const dir = path.resolve(args.slice(1).find((a) => !a.startsWith('--')) ?? 'dashboards');
  if (watch) {
    watchDashboards(dir).ref();
  } else {
    console.log(writeIndex(dir) ? `wrote ${path.join(dir, INDEX)}` : `${path.join(dir, INDEX)} is up to date`);
  }
}
