#!/usr/bin/env node
// Generates JSON Schemas for app configs from modelform's TypeScript types, so editors and
// the app agree with what the renderer reads:
//
//   schema/app.schema.json             the manifest (strict: unknown keys are flagged)
//   schema/dashboard.schema.json       dashboards and forms (loose: Grafana exports carry many keys modelform ignores)
//   src/core/generated/validators.js   both, compiled ahead of time by Ajv so validating needs no eval (Hermes)
//
// Run `pnpm schema` after changing the types; a test fails while they're stale.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const TSCONFIG = path.join(ROOT, 'tsconfig.json');
const APP_ID = 'urn:modelform:app';
const DASHBOARD_ID = 'urn:modelform:dashboard';

/** Offered as completions for `panel.type`. Others are allowed: apps can registerPanel() their own. */
const PANEL_TYPES = [
  'row', 'timeseries', 'trend', 'xychart', 'stat', 'gauge', 'bargauge', 'piechart', 'barchart', 'table', 'text', 'geomap',
  'input-number', 'input-slider', 'input-select', 'input-toggle', 'input-rating', 'input-text', 'input-counter', 'input-duration',
];

function generate(file, type, additionalProperties) {
  const { createGenerator } = require('ts-json-schema-generator');
  return createGenerator({
    path: path.join(ROOT, 'src/core', file),
    tsconfig: TSCONFIG,
    type,
    expose: 'export',
    topRef: true,
    jsDoc: 'extended',
    additionalProperties,
    skipTypeCheck: true,
  }).createSchema(type);
}

/** Drops definitions nothing reachable from the root refers to. */
function prune(schema) {
  const keep = new Set();
  const walk = (node) => {
    if (Array.isArray(node)) return node.forEach(walk);
    if (!node || typeof node !== 'object') return;
    const ref = typeof node.$ref === 'string' && node.$ref.match(/^#\/definitions\/(.+)$/);
    if (ref && !keep.has(decodeURIComponent(ref[1]))) {
      keep.add(decodeURIComponent(ref[1]));
      walk(schema.definitions[decodeURIComponent(ref[1])]);
    }
    for (const [k, v] of Object.entries(node)) if (k !== 'definitions') walk(v);
  };
  walk(schema);
  schema.definitions = Object.fromEntries(Object.entries(schema.definitions).filter(([k]) => keep.has(k)));
  return schema;
}

function dashboardSchema() {
  const schema = generate('schema.ts', 'Dashboard', true);
  Object.assign(schema.definitions, generate('inputs.ts', 'InputOptions', true).definitions);
  const panel = schema.definitions.Panel;
  panel.properties.type.examples = PANEL_TYPES;
  // Input panels record to options.metric, so they need options shaped like InputOptions.
  panel.allOf = [
    {
      if: { properties: { type: { pattern: '^input-' } }, required: ['type'] },
      then: { required: ['options'], properties: { options: { $ref: '#/definitions/InputOptions' } } },
    },
  ];
  return { $schema: schema.$schema, $id: DASHBOARD_ID, title: 'modelform dashboard or form', ...schema };
}

function appSchema() {
  const schema = generate('manifest.ts', 'AppManifest', false);
  // Inline documents are dashboards, checked loosely by the dashboard schema.
  schema.definitions.Dashboard = { $ref: DASHBOARD_ID };
  schema.definitions.AppManifest.properties.version = { ...schema.definitions.AppManifest.properties.version, const: 1 };
  delete schema.definitions.AppManifest.properties.version.type;
  return prune({ $schema: schema.$schema, $id: APP_ID, title: 'modelform app config', ...schema });
}

function validatorsSource(app, dashboard) {
  const Ajv = require('ajv').default;
  const standalone = require('ajv/dist/standalone').default;
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } });
  ajv.addSchema(dashboard).addSchema(app);
  // Ajv's ESM output still require()s its runtime helpers. Inline the one minLength uses
  // (string length in code points) so the module stands alone under Metro and Vitest alike.
  const code = standalone(ajv, { validateApp: APP_ID, validateDashboard: DASHBOARD_ID }).replaceAll(
    'require("ajv/dist/runtime/ucs2length").default',
    '((s) => { let n = 0; for (const _ of s) n++; return n; })',
  );
  const leftover = code.match(/require\("[^"]+"\)/);
  if (leftover) throw new Error(`validators.js needs ${leftover[0]}: inline it in tools/schema.js`);
  return `// Generated by tools/schema.js from schema/*.schema.json. Do not edit.\n/* eslint-disable */\n${code}`;
}

/** Every generated file's path and contents. */
function outputs() {
  const app = appSchema();
  const dashboard = dashboardSchema();
  const json = (s) => JSON.stringify(s, null, 2) + '\n';
  return {
    'schema/app.schema.json': json(app),
    'schema/dashboard.schema.json': json(dashboard),
    'src/core/generated/validators.js': validatorsSource(app, dashboard),
  };
}

/** Files whose contents on disk differ from what would be generated now. */
function stale() {
  return Object.entries(outputs())
    .filter(([file, text]) => {
      try {
        return fs.readFileSync(path.join(ROOT, file), 'utf8') !== text;
      } catch {
        return true;
      }
    })
    .map(([file]) => file);
}

module.exports = { outputs, stale, APP_ID, DASHBOARD_ID };

if (require.main === module) {
  for (const [file, text] of Object.entries(outputs())) {
    fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, file), text);
    console.log(`modelform: wrote ${file}`);
  }
}
